/*
  Unified download menu — browser WASM compilation + source exports.
*/

function convertToPython(jsCode) {
  return '# Generated by Lighthouse — review before running\n' +
    String(jsCode)
      .replace(/const /g, '')
      .replace(/let /g, '')
      .replace(/var /g, '')
      .replace(/function /g, 'def ')
      .replace(/console\.log/g, 'print')
      .replace(/===/g, '==')
      .replace(/!==/g, '!=')
      .replace(/\{/g, ':')
      .replace(/\}/g, '');
}

function showToast(msg, duration = 3200) {
  let toast = document.querySelector('.toast');
  if (!toast) {
    toast = document.createElement('div');
    toast.className = 'toast';
    document.body.appendChild(toast);
  }
  toast.textContent = msg;
  toast.classList.add('show');
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => toast.classList.remove('show'), duration);
}

function downloadBlob(content, filename, mime = 'application/octet-stream') {
  const blob = content instanceof Blob
    ? content
    : new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function closeDownloadMenu() {
  const existing = document.getElementById('frontierDownloadOverlay');
  if (existing) existing.remove();
}

async function detectAvailableTargets() {
  const targets = [
    { id: 'source', label: '📄 Source Code', ext: '.fr', action: 'download', always: true },
    { id: 'javascript', label: '📄 JavaScript', ext: '.js', action: 'download', always: true },
    { id: 'python', label: '📄 Python', ext: '.py', action: 'download', always: true }
  ];

  if (window.BrowserCompiler) {
    await window.BrowserCompiler.init();
    if (window.BrowserCompiler.isAvailable()) {
      const wasmTargets = await window.BrowserCompiler.getTargets();
      wasmTargets.forEach(t => {
        targets.push({
          id: t.id,
          label: `⚡ ${t.label}${t.recommended ? ' (recommended)' : ''}`,
          ext: t.ext || '',
          action: 'compile-browser',
          target: t.id,
          zeroDeps: true,
          inBrowser: true
        });
      });
    }
  }

  try {
    const res = await fetch('/api/frontier/status');
    const status = await res.json();
    if (status.compiler || status.compilerAvailable) {
      targets.push({
        id: 'native-server',
        label: '🔧 Native Binary (server compiled)',
        ext: '',
        action: 'compile-server',
        zeroDeps: false
      });
    }
  } catch {}

  return targets;
}

function renderDownloadOptions(container, targets, file) {
  container.innerHTML = targets.map(t => `
    <button type="button" class="download-option" data-action="${t.action}" data-id="${t.id}"
      data-ext="${t.ext || ''}" data-target="${t.target || ''}">
      <div class="download-option-label">${t.label}</div>
      <div class="download-option-meta">
        <span class="download-option-ext">${t.ext || 'binary'}</span>
        ${t.zeroDeps ? '<span class="badge-zero">ZERO DEPS</span>' : ''}
        ${t.inBrowser ? '<span class="badge-browser">IN BROWSER</span>' : ''}
      </div>
    </button>
  `).join('');

  container.querySelectorAll('.download-option').forEach(btn => {
    btn.addEventListener('click', () => handleDownloadOption(btn.dataset, file));
  });
}

async function handleDownloadOption(dataset, file) {
  const { action, id, ext, target } = dataset;
  const base = file.path.split('/').pop().replace(/\.[^.]+$/, '');

  switch (action) {
    case 'download': {
      let content = file.content;
      if (id === 'python') content = convertToPython(file.content);
      const useExt = id === 'source' ? (file.path.endsWith('.fr') ? '.fr' : '.fr') : ext;
      downloadBlob(content, base + useExt, 'text/plain');
      showToast(`✅ Downloaded ${base}${useExt}`);
      break;
    }
    case 'compile-browser': {
      showToast('⚡ Compiling in browser...');
      const result = await window.BrowserCompiler.compile(file.content, target);
      if (!result.success) {
        showToast(`❌ ${result.error || 'Compilation failed'}`);
        return;
      }
      const outExt = ext || (target.includes('windows') ? '.exe' : target.includes('apk') ? '.apk' : '');
      const filename = result.filename || `${base}-${target}${outExt}`;
      window.BrowserCompiler.downloadBinary(result.binary, filename);
      const kb = (result.size / 1024).toFixed(1);
      showToast(`✅ ${target} (${kb} KB) — ${result.compiledIn}`);
      break;
    }
    case 'compile-server': {
      showToast('🔧 Compiling on server...');
      const res = await fetch('/api/frontier/compile', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ source: file.content, code: file.content, target: target || 'native', language: 'frontier', filename: file.path })
      });
      const data = await res.json();
      if (!data.ok) {
        showToast(`❌ ${data.error || 'Server compile failed'}`);
        return;
      }
      const bytes = Uint8Array.from(atob(data.binary), c => c.charCodeAt(0));
      downloadBlob(bytes, data.filename || `${base}-native`);
      showToast('✅ Native binary ready (server)');
      break;
    }
    default:
      break;
  }

  closeDownloadMenu();
}

async function showDownloadMenu(file) {
  if (!file) {
    showToast('Select a file first');
    return;
  }

  closeDownloadMenu();

  const overlay = document.createElement('div');
  overlay.id = 'frontierDownloadOverlay';
  overlay.className = 'download-overlay';
  overlay.innerHTML = `
    <div class="download-menu-modal">
      <div class="download-menu-header">
        <span>⬇️ Download: ${file.path}</span>
        <button type="button" class="download-menu-close" aria-label="Close">✕</button>
      </div>
      <div class="download-options" id="downloadOptions">
        <div class="download-loading">🔍 Detecting available formats...</div>
      </div>
    </div>
  `;

  document.body.appendChild(overlay);
  overlay.querySelector('.download-menu-close').onclick = closeDownloadMenu;
  overlay.addEventListener('click', e => { if (e.target === overlay) closeDownloadMenu(); });

  const container = overlay.querySelector('#downloadOptions');
  const targets = await detectAvailableTargets();
  renderDownloadOptions(container, targets, file);
}

window.showDownloadMenu = showDownloadMenu;
window.showToast = showToast;
window.closeDownloadMenu = closeDownloadMenu;
